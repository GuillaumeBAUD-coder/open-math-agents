#!/usr/bin/env python3
"""Writes .github/workflows/batch-check.yml (run it after changing anything below; the workflow file is generated).

A job of the batch checker restores the Lean tree once, starts tools/batch_check.sh in the background and then runs
ROUNDS identical pairs of steps: "publish" (waits up to two minutes for new verdicts) and an upload of the artifact
bv-<shard> (overwritten each time; the merger reads the newest). GitHub Actions has no loop over steps, hence the
generated list. Usage: python3 tools/batch_check_yml.py > .github/workflows/batch-check.yml
"""
SHARDS = 8          # parallel jobs; pull request n goes to shard n % SHARDS (tools/batch_verdicts.sh reads this line)
PREV_SHARDS = 4     # the shard count before the last change: a new shard starts from the state of shard % PREV_SHARDS
LANES = 3           # checks at once in a job (one Lean check uses ~1 of the 4 cores and ~0.5 GB of its own memory)
ROUNDS = 100        # publish rounds per job: new verdicts go out at most once a minute, a round waits 2 minutes at most
JOB_MINUTES = 120   # no new check starts after this; the job then publishes and ends (the next run takes over)

HEAD = f"""# GENERATED by tools/batch_check_yml.py: edit that file, not this one.
# Batch checker: each job restores the Lean tree once and checks many pull requests, each in its own sandbox
# (tools/batch_check.sh: bubblewrap, no network, no token, read-only toolchain and Mathlib, a throw-away copy of
# formal-conjectures). Verdicts are check-proof.yml's, step for step; they go out as the artifact bv-<shard>, which
# the merger (tools/batch_verdicts.sh) reads only from runs of this workflow on main and gives through
# tools/verdict_one.sh exactly like a check-proof verdict. Trusted: runs code from main; pull request content is only
# ever read as data or compiled inside the sandbox. check-proof.yml stays as it was until this path is proven.
name: batch-check
on:
  schedule:
    - cron: "*/30 * * * *"
  workflow_dispatch:
  push:
    branches: [main]
    paths: [".github/workflows/batch-check.yml"]
permissions:
  contents: read
  actions: read   # the previous job's artifact: which pull requests already have a verdict
concurrency:
  group: batch-check
  cancel-in-progress: false
jobs:
  check:
    runs-on: ubuntu-latest
    timeout-minutes: {JOB_MINUTES + 45}
    strategy:
      fail-fast: false
      matrix:
        shard: [{", ".join(str(i) for i in range(SHARDS))}]
    env:
      ELAN_HOME: /mnt/oma/elan
      OMA_FC: /mnt/oma/fc
      BC: /mnt/oma/batch
      SHARD: ${{{{ matrix.shard }}}}
      SHARDS: "{SHARDS}"
      LANES: "{LANES}"
    steps:
      - uses: actions/checkout@v4
        with:
          ref: main
          fetch-depth: 1
          persist-credentials: false   # no token on disk: the worker reads public refs anonymously
          sparse-checkout: |
            tools
            data
            reductions
            statements
      - name: Sandbox (bubblewrap) and work directory
        run: |
          sudo mkdir -p /mnt/oma && sudo chown "$(id -u):$(id -g)" /mnt/oma
          command -v bwrap > /dev/null || {{ sudo apt-get update -qq && sudo apt-get install -y -qq bubblewrap > /dev/null; }}
          # Ubuntu 24.04 confines unprivileged user namespaces with AppArmor; bubblewrap needs them
          sudo sysctl -q -w kernel.apparmor_restrict_unprivileged_userns=0 || true
          bwrap --unshare-all --die-with-parent --ro-bind /usr /usr --symlink usr/bin /bin --symlink usr/lib /lib \\
            --symlink usr/lib64 /lib64 --proc /proc --dev /dev --tmpfs /tmp /usr/bin/true
          # the worker runs from a copy: the checkout is refreshed to the newest main while it runs
          mkdir -p "$BC" && cp tools/batch_check.sh "$BC/batch_check.sh"
      - name: Pinned formal-conjectures
        id: fc
        run: |
          C=$(python3 -I -c 'import json;print(json.load(open("data/catalog.json"))["meta"]["upstreamCommit"])')
          echo "commit=$C" >> "$GITHUB_OUTPUT"
          git init -q "$OMA_FC" && cd "$OMA_FC"
          git remote add origin https://github.com/google-deepmind/formal-conjectures
          git fetch -q --depth 1 origin "$C" && git checkout -q FETCH_HEAD
      - uses: actions/cache/restore@v4
        id: cache
        with:
          path: |
            /mnt/oma/elan
            /mnt/oma/fc/.lake
          key: lean-mnt-v1-${{{{ steps.fc.outputs.commit }}}}
          fail-on-cache-miss: true   # the prebuilt tree (warm-lean-cache.yml) or nothing: check-proof covers the gap
      - name: Verdicts the previous job of this shard already gave
        env:
          GH_TOKEN: ${{{{ github.token }}}}
          REPO: ${{{{ github.repository }}}}
        run: |
          # only an artifact of this workflow, run on main by a schedule, a dispatch or a push: an artifact of the same
          # name uploaded by a pull request's run is ignored
          # (no answer from the API: stop here rather than start afresh and check again what was already checked)
          # A shard without an artifact yet (the shard count just grew) starts from the one that held its pull requests.
          GOT=0
          for NAME in "bv-$SHARD" "bv-$(( SHARD % {PREV_SHARDS} ))"; do
            [ "$GOT" = 0 ] || break
            A=$(gh api "repos/$REPO/actions/artifacts?name=$NAME&per_page=10" --jq '.artifacts[] | select(.expired | not) | [.id, .workflow_run.id] | @tsv') || {{ echo "cannot list artifacts"; exit 1; }}
            while IFS=$'\\t' read -r AID RID; do
              [ -n "$AID" ] || continue
              OK=$(gh api "repos/$REPO/actions/runs/$RID" --jq 'select(.path == ".github/workflows/batch-check.yml" and .head_branch == "main" and (.event == "schedule" or .event == "workflow_dispatch" or .event == "push") and .repository.full_name == .head_repository.full_name) | .id' 2>/dev/null || true)
              [ "$OK" = "$RID" ] || continue
              mkdir -p /tmp/prev && gh api "repos/$REPO/actions/artifacts/$AID/zip" > /tmp/prev/a.zip && (cd /tmp/prev && unzip -o -q a.zip) || continue
              cp /tmp/prev/done.tsv "$BC/done.tsv"; cp /tmp/prev/verdicts.jsonl "$BC/verdicts.jsonl"
              [ -s /tmp/prev/since.txt ] && cp /tmp/prev/since.txt "$BC/since.txt"
              echo "inherited $(wc -l < "$BC/done.tsv") verdicts of $NAME from run $RID"; GOT=1; break
            done <<< "$A"
          done
          wc -l < "$BC/verdicts.jsonl" 2>/dev/null > "$BC/published.count" || echo 0 > "$BC/published.count"
      - name: Start the worker
        run: |
          export WS="$GITHUB_WORKSPACE"
          export BATCH_DEADLINE=$(( $(date -u +%s) + {JOB_MINUTES} * 60 ))
          nohup setsid bash "$BC/batch_check.sh" worker > "$BC/worker.log" 2>&1 < /dev/null &
          echo "BV_STARTED=1" >> "$GITHUB_ENV"
          sleep 5; cat "$BC/worker.log"
"""

ROUND = """      - name: Publish {n}
        run: WS="$GITHUB_WORKSPACE" bash "$BC/batch_check.sh" publish
      - uses: actions/upload-artifact@v4
        if: env.BV_CHANGED == '1'
        with:
          name: bv-${{{{ matrix.shard }}}}
          path: /mnt/oma/batch/pub/
          overwrite: true
          retention-days: 7
"""

TAIL = """      - name: Stop
        if: ${{ always() && env.BV_STARTED == '1' }}   # never overwrite the state with an empty one
        run: WS="$GITHUB_WORKSPACE" bash "$BC/batch_check.sh" stop
      - uses: actions/upload-artifact@v4
        if: ${{ always() && env.BV_STARTED == '1' }}   # never overwrite the state with an empty one
        with:
          name: bv-${{ matrix.shard }}
          path: /mnt/oma/batch/pub/
          overwrite: true
          retention-days: 7
"""

if __name__ == "__main__":
    print(HEAD + "".join(ROUND.format(n=i + 1) for i in range(ROUNDS)) + TAIL, end="")
